# Regenerates data\ggg_passive_ids.tsv: GGG passive string ids (used by .build files) -> PoB2 node hashes.
# Source: GGG's official tree export (github.com/grindinggear/poe2-skilltree-export, data.json).
# Usage: powershell -File tools\make-passive-ids.ps1 [path\to\data.json] [PoB2 tree.lua to verify against]
param(
    [string]$DataJson = "$env:TEMP\ggg-poe2-tree.json",
    [string]$PobTree = 'D:\Path of Building Community (PoE2)\TreeData\0_5\tree.lua'
)
$ErrorActionPreference = 'Stop'
if (-not (Test-Path $DataJson)) {
    Invoke-WebRequest 'https://raw.githubusercontent.com/grindinggear/poe2-skilltree-export/main/data.json' -OutFile $DataJson -UseBasicParsing
}
Add-Type -AssemblyName System.Web.Extensions
$js = New-Object Web.Script.Serialization.JavaScriptSerializer
$js.MaxJsonLength = [int]::MaxValue
$d = $js.DeserializeObject([IO.File]::ReadAllText($DataJson))

# PoB2 node blocks keyed by hash; a block holds the node's own name (switchable nodes add option names).
$pob = @{}
if (Test-Path $PobTree) {
    $lua = [IO.File]::ReadAllText($PobTree)
    foreach ($m in [regex]::Matches($lua, '\[(\d+)\]=\{[\s\S]*?\bskill=\1,')) { $pob[[int]$m.Groups[1].Value] = $m.Value }
}

$out = New-Object Collections.Generic.List[string]
$out.Add('# GGG passive id -> PoB2 node hash. Generated by tools\make-passive-ids.ps1 from GGG poe2-skilltree-export data.json.')
$out.Add('# Rows: id<TAB>hash<TAB>name. "#class" rows: #class<TAB>integerId<TAB>class<TAB>ascendancyId=name,...')
$i = 0
foreach ($c in $d['classes']) {
    $asc = @($c['ascendancies'] | ForEach-Object { $_['id'] + '=' + $_['name'] }) -join ','
    $out.Add("#class`t$i`t$($c['name'])`t$asc")
    $i++
}
$checked = 0; $mismatch = 0
foreach ($n in $d['nodes'].Values) {
    if (-not ($n -is [Collections.IDictionary]) -or -not $n.ContainsKey('id') -or -not $n.ContainsKey('skill')) { continue }
    $name = [string]$n['name']
    $out.Add("$($n['id'])`t$($n['skill'])`t$name")
    if ($pob.Count -gt 0 -and $pob.ContainsKey([int]$n['skill'])) {
        $checked++
        $plain = [regex]::Replace($name, '\[(?:[^|\]]*\|)?([^\]]*)\]', '$1')
        if ($pob[[int]$n['skill']].IndexOf('name="' + $plain + '"') -lt 0) { $mismatch++; if ($mismatch -le 10) { "Name differs: $($n['id']) $plain" } }
    }
}
$target = Join-Path (Split-Path $PSScriptRoot) 'data\ggg_passive_ids.tsv'
New-Item -ItemType Directory -Force -Path (Split-Path $target) | Out-Null
[IO.File]::WriteAllLines($target, $out)
"Wrote $($out.Count) lines to $target. PoB2 nodes: $($pob.Count); GGG hashes found in PoB2: $checked; name mismatches: $mismatch"
